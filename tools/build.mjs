// Build step (no bundler): embeds the built-in packs, renders PNG icons, writes the service worker
// with a content-hashed precache list, and prints a byte-size report.
// Run from tools/: node build.mjs [--icons]
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';

const app = new URL('../app/', import.meta.url).pathname;
const read = (f) => fs.readFileSync(app + f);

// 1. built-in packs -> js/packs.js (works from file:// too, no fetch needed)
const order = ['g5-fractions', 'g5-water-cycle', 'g4-english-sentence'];
const packs = order.map((id) => JSON.parse(read('packs/' + id + '.ekpack.json')));
// Real byte size of the lazy Urdu font, so the "Save Urdu font" button never shows a guessed number.
const urduFontBytes = fs.statSync(app + 'fonts/nastaliq-urdu-subset.woff2').size;
fs.writeFileSync(app + 'js/packs.js', '/* Generated by tools/build.mjs from app/packs/*.ekpack.json. Do not edit. */\nself.EK_BUILTIN=' + JSON.stringify(packs) + ';\nself.EK_ASSET_BYTES=' + JSON.stringify({ 'fonts/nastaliq-urdu-subset.woff2': urduFontBytes }) + ';\n');

// 2. icons
if (process.argv.includes('--icons')) {
  const { launch } = await import('./pw.mjs');
  const b = await launch();
  const pg = await b.newPage();
  const svg = read('icons/icon.svg').toString();
  for (const [name, sz, pad] of [['icon-192.png', 192, 0], ['icon-512.png', 512, 0], ['icon-maskable-512.png', 512, 0.12]]) {
    await pg.setViewportSize({ width: sz, height: sz });
    await pg.setContent(`<body style="margin:0;background:#F6F1E7;display:grid;place-items:center;height:${sz}px"><div style="width:${sz * (1 - pad * 2)}px;height:${sz * (1 - pad * 2)}px">${svg.replace('<svg ', '<svg width="100%" height="100%" ')}</div></body>`);
    await pg.screenshot({ path: app + 'icons/' + name });
  }
  await b.close();
}

// 3. service worker
const precache = [
  './', 'index.html', 'manifest.webmanifest', 'css/kaghaz.css', 'css/urdu.css',
  'js/i18n.js', 'js/storage.js', 'js/qrchunk.js', 'js/art.js', 'js/packs.js', 'js/app.js',
  'vendor/qrcode-generator.min.js', 'vendor/jsQR.min.js',
  'fonts/atkinson-400.woff2', 'fonts/atkinson-700.woff2', 'fonts/literata-600.woff2',
  'icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png',
  'samples/g3-plant-parts.ekpack.json'
];
const hash = crypto.createHash('sha256');
for (const f of precache) if (f !== './') hash.update(read(f));
hash.update(read('fonts/nastaliq-urdu-subset.woff2'));
const version = hash.digest('hex').slice(0, 10);
fs.writeFileSync(app + 'sw.js', `/* Ek Phone service worker. Generated by tools/build.mjs. */
'use strict';
var VERSION = 'ekphone-${version}';
var PRECACHE = ${JSON.stringify(precache)};
var LAZY = ['fonts/nastaliq-urdu-subset.woff2']; // Urdu font: cached the first time Urdu is used
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(VERSION).then(function (c) { return c.addAll(PRECACHE); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) { return Promise.all(keys.filter(function (k) { return k.indexOf('ekphone-') === 0 && k !== VERSION; }).map(function (k) { return caches.delete(k); })); }).then(function () { return self.clients.claim(); }));
});
self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('index.html').then(function (r) { return r || fetch(req); }).catch(function () { return caches.match('index.html'); }));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(function (hit) {
    if (hit) return hit;
    return fetch(req).then(function (res) {
      if (res.ok && LAZY.some(function (p) { return req.url.indexOf(p) >= 0; })) { var copy = res.clone(); caches.open(VERSION).then(function (c) { c.put(req, copy); }); }
      return res;
    });
  }));
});
`);

// 4. size report
const sz = (f) => fs.statSync(app + f).size;
const groups = {
  'shell (first screen: HTML+CSS+own JS)': ['index.html', 'css/kaghaz.css', 'js/i18n.js', 'js/storage.js', 'js/qrchunk.js', 'js/art.js', 'js/app.js', 'manifest.webmanifest', 'sw.js'],
  'built-in lesson packs (js/packs.js)': ['js/packs.js'],
  'lazy: QR encoder (share screen only)': ['vendor/qrcode-generator.min.js'],
  'lazy: jsQR scanner fallback (only if no BarcodeDetector)': ['vendor/jsQR.min.js'],
  'Latin fonts (always)': ['fonts/atkinson-400.woff2', 'fonts/atkinson-700.woff2', 'fonts/literata-600.woff2'],
  'lazy: Urdu font + css (only when Urdu is on)': ['fonts/nastaliq-urdu-subset.woff2', 'css/urdu.css'],
  'icons': ['icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png']
};
const zlib = await import('node:zlib');
const report = { generated: new Date().toISOString(), version, groups: {}, files: {} };
let total = 0;
for (const [g, files] of Object.entries(groups)) {
  let s = 0, gz = 0;
  for (const f of files) { if (!fs.existsSync(app + f)) continue; const b = read(f); s += b.length; gz += zlib.gzipSync(b, { level: 9 }).length; report.files[f] = { bytes: b.length, gzip: zlib.gzipSync(b, { level: 9 }).length }; }
  report.groups[g] = { bytes: s, gzip: gz, kb: +(s / 1024).toFixed(1), gzipKb: +(gz / 1024).toFixed(1) };
  total += s;
}
for (const id of order) report.files['packs/' + id + '.ekpack.json (minified JSON)'] = { bytes: Buffer.byteLength(JSON.stringify(JSON.parse(read('packs/' + id + '.ekpack.json')))) };
report.totalBytesEverything = total; report.totalKb = +(total / 1024).toFixed(1);
const shell = report.groups['shell (first screen: HTML+CSS+own JS)'].bytes;
report.shellBudget = { limitBytes: 150 * 1024, shellBytes: shell, pass: shell <= 150 * 1024 };
const evid = new URL('../evidence/', import.meta.url).pathname; fs.mkdirSync(evid, { recursive: true });
fs.writeFileSync(evid + 'size-report.json', JSON.stringify(report, null, 2));
let md = `# Byte-size report\n\nGenerated ${report.generated} by tools/build.mjs (uncompressed bytes; gzip -9 in brackets).\n\n| Group | Size | gzip |\n|---|---|---|\n`;
for (const [g, v] of Object.entries(report.groups)) md += `| ${g} | ${v.kb} KB | ${v.gzipKb} KB |\n`;
md += `| **Everything (incl. fonts, icons, lazy parts)** | **${report.totalKb} KB** | |\n\nShell budget ≤150 KB: **${report.shellBudget.pass ? 'PASS' : 'FAIL'}** (${(shell / 1024).toFixed(1)} KB).\n\n## Files\n\n| File | Bytes | gzip |\n|---|---|---|\n`;
for (const [f, v] of Object.entries(report.files)) md += `| ${f} | ${v.bytes} | ${v.gzip ?? ''} |\n`;
fs.writeFileSync(evid + 'size-report.md', md);
console.log(md);
